WIDTH = 5
HEIGHT = 7


def glyph(ch: str):
    return GLYPH_ROWS.get(ch.upper(), GLYPH_ROWS["?"])


def text_width(text: str, scale: int = 1, spacing: int = 1) -> int:
    return len(text) * (WIDTH + spacing) * scale


def draw_text(canvas, x: int, y: int, text: str, color, scale: int = 1, spacing: int = 1):
    """Draw text on a canvas object exposing put(x, y, color)."""
    cx = x
    for ch in text:
        rows = glyph(ch)
        for gy in range(HEIGHT):
            for gx in range(WIDTH):
                if rows[gy][gx] == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            canvas.put(cx + gx * scale + sx, y + gy * scale + sy, color)
        cx += (WIDTH + spacing) * scale
    return cx
