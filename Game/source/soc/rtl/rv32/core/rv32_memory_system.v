                            i_valid<=instruction_valid[i_next_index];
                            i_second_tag<=instruction_tags_second[i_next_index];
                            i_second_valid<=I_WAYS>1 && instruction_valid_second[i_next_index];
                            i_lru<=instruction_lru[i_next_index];
                        end
                    end else if (i_complete) i_state<=I_IDLE;
                end
                I_COMMAND: if (instr_gnt_i) begin
                    i_state<=I_FILL;
                    i_beat<=0; i_fill_error<=0;
                    if (instr_rvalid_i) begin
                        // RAM write is in the common bank-port process below.
                        // RAM write is in the common bank-port process below.
                        if(i_address[5:3]==0)begin
                            begin i_odd_bypass<=instr_rdata_i[63:32]; i_odd_ram_select<=1'b0; end
                            if(!i_address[2])begin i_even_bypass<=instr_rdata_i[31:0]; i_even_ram_select<=1'b0; end
                        end
                        i_beat<=1; i_fill_error<=instr_err_i;
                    end
                end
                I_FILL: if (instr_rvalid_i) begin
                    // RAM write is in the common bank-port process below.
                    // RAM write is in the common bank-port process below.
                    if(i_beat==i_address[5:3])begin
                        begin i_odd_bypass<=instr_rdata_i[63:32]; i_odd_ram_select<=1'b0; end
                        if(!i_address[2])begin i_even_bypass<=instr_rdata_i[31:0]; i_even_ram_select<=1'b0; end
                    end
                    if(i_address[2] && i_address[5:3]!=3'd7 && i_beat==(i_address[5:3]+3'd1))
                        begin i_even_bypass<=instr_rdata_i[31:0]; i_even_ram_select<=1'b0; end
                    i_fill_error<=i_fill_error || instr_err_i;
                    if (i_beat==3'd7) begin
                        if (i_fill_error || instr_err_i) begin
                            if (!i_crossing && i_address[5:2]==4'd15 && executable(i_next_address)) begin
                                i_first_word<=0; i_first_error<=1; i_crossing<=1;
                                i_address<=i_next_address;
                                i_even_ram_select<=1'b1;
                                i_odd_ram_select<=1'b1;
                                i_tag<=instruction_tags[i_next_index];
                                i_valid<=instruction_valid[i_next_index];
                                i_second_tag<=instruction_tags_second[i_next_index];
                                i_second_valid<=I_WAYS>1 && instruction_valid_second[i_next_index];
                                i_lru<=instruction_lru[i_next_index];
                                i_state<=I_LOOKUP;
                            end else begin
                                begin i_error_data_snapshot<=i_crossing ? {32'b0,i_first_word} : 64'b0;i_error_word_valid<=i_crossing;end
                                i_error_bits<=i_crossing ? {1'b1,i_first_error} : 2'b11;
                                i_state<=I_ERROR;
                            end
                        end else begin
                            if(I_WAYS>1 && i_refill_way)begin
                                instruction_tags_second[i_index]<=i_address[31:6+I_INDEX_BITS];
                                instruction_valid_second[i_index]<=1'b1;
                                i_second_tag<=i_address[31:6+I_INDEX_BITS];i_second_valid<=1;
                                if(!instruction_valid[i_index])begin
                                    instruction_tags[i_index]<=~i_address[31:6+I_INDEX_BITS];
                                    i_tag<=~i_address[31:6+I_INDEX_BITS];
                                end
                            end else begin
                                instruction_tags[i_index]<=i_address[31:6+I_INDEX_BITS];
                                instruction_valid[i_index]<=1'b1;
                                i_tag<=i_address[31:6+I_INDEX_BITS]; i_valid<=1;
                                if(I_WAYS>1 && !instruction_valid_second[i_index])begin
                                    instruction_tags_second[i_index]<=~i_address[31:6+I_INDEX_BITS];
                                    i_second_tag<=~i_address[31:6+I_INDEX_BITS];
                                end
                            end
                            i_state<=I_LOOKUP;
                        end
                    end else i_beat<=i_beat+3'd1;
                end
                I_ERROR: if (i_complete) i_state<=I_IDLE;
                default: begin end
            endcase
            // Acceptance has priority over completing the previous response.
            // A hit can therefore accept the next request on the same edge.
            if (new_i) begin
                i_address<=imem_request_address;
                i_crossing<=0; i_first_error<=0;
                if (!executable(imem_request_address) || imem_request_address[1:0]!=0) begin
                    i_state<=I_ERROR; i_error_bits<=2'b11; begin i_error_data_snapshot<=0;i_error_word_valid<=0;end
                end else begin
                    i_state<=I_LOOKUP;
                end
            end

            if(i_speculative_read)begin
                // Snapshot both tags at exactly the payload-read edge. No
                // maintenance can complete while an instruction is owned.
                // A refill of word0 cannot modify the distinct word1 index.
                if(ENABLE_FAST_ICROSS)begin
                    i_next_tag<=instruction_tags[new_i_next_index];
                    i_next_valid<=instruction_valid[new_i_next_index];
                    i_next_second_tag<=instruction_tags_second[new_i_next_index];
                    i_next_second_valid<=I_WAYS>1 && instruction_valid_second[new_i_next_index];
                end
                i_even_ram_select<=1'b1;i_odd_ram_select<=1'b1;
                i_tag<=instruction_tags[imem_request_address[6+I_INDEX_BITS-1:6]];
                i_valid<=instruction_valid[imem_request_address[6+I_INDEX_BITS-1:6]];
                i_second_tag<=instruction_tags_second[imem_request_address[6+I_INDEX_BITS-1:6]];
                i_second_valid<=I_WAYS>1 && instruction_valid_second[imem_request_address[6+I_INDEX_BITS-1:6]];
                i_lru<=instruction_lru[imem_request_address[6+I_INDEX_BITS-1:6]];
                if(i_complete && i_state==I_LOOKUP)begin
                    if(imem_request_address[6+I_INDEX_BITS-1:6]==i_index)i_lru<=!i_hit_way;
                    if(i_fast_cross_hit && imem_request_address[6+I_INDEX_BITS-1:6]==i_next_index)i_lru<=!i_next_hit_way;
                end
            end
            // Touch only owned, consumed lines, including both halves of a
            // fast cross-line response. Held responses retain their payload.
            if(i_state==I_LOOKUP && i_hit && (i_complete || i_ram_cross_lookup))
                instruction_lru[i_index]<=!i_hit_way;
            if(i_state==I_LOOKUP && i_hit && i_complete && i_fast_cross_hit)
                instruction_lru[i_next_index]<=!i_next_hit_way;
            case (d_state)
                D_IDLE: if (fence_pending && i_state==I_IDLE) begin
                    sweep_index<=0; sweep_way<=0; d_state<=D_SWEEP_READ;
                end
                D_LOOKUP: begin
                    if (d_hit) begin
                        if (d_complete) begin
                            if (d_write) begin
                                if(selected_way)begin
                                    // Store byte enables use the common RAM write port.
                                    data_dirty_second[d_index]<=1'b1;
                                end else begin
                                    // Store byte enables use the common RAM write port.
                                    data_dirty[d_index]<=1'b1;
                                end
                            end
                            data_lru[d_index]<=!selected_way;
                            d_state<=D_IDLE;
                        end
                    end else if (selected_valid && selected_dirty) begin
                        request_way<=selected_way;
                        writeback_way<=selected_way;
                        writeback_address<={selected_tag,d_index,6'b0};
                        writeback_index<=d_index;
                        writeback_is_sweep<=0;
                        d_beat<=0; d_state<=D_WRITE_READ;
                    end else begin
                        request_way<=selected_way;
                        d_beat<=0; d_fill_error<=0; d_state<=D_READ_COMMAND;
                    end
                end
                D_READ_COMMAND: if (data_rd_gnt_i) begin
                    d_state<=D_FILL; d_beat<=0; d_fill_error<=0;
                    if(request_way)data_valid_second[d_index]<=0;
                    else data_valid[d_index]<=0;
                    if (data_rd_rvalid_i) begin
                        if(request_way)begin
                            // Refill uses the common RAM write port.
                            if(d_address[5:3]==0)begin d_second_bypass<=data_rd_rdata_i; d_second_ram_select<=1'b0; end
                        end else begin
                            // Refill uses the common RAM write port.
                            if(d_address[5:3]==0)begin d_first_bypass<=data_rd_rdata_i; d_first_ram_select<=1'b0; end
                        end
                        d_beat<=1;
                        d_fill_error<=data_rd_err_i || data_rd_rid_i!=1'b0;
                    end
                end
                D_FILL: if (data_rd_rvalid_i) begin
                    if(request_way)begin
                        // Refill uses the common RAM write port.
                        if(d_beat==d_address[5:3])begin d_second_bypass<=data_rd_rdata_i; d_second_ram_select<=1'b0; end
                    end else begin
                        // Refill uses the common RAM write port.
                        if(d_beat==d_address[5:3])begin d_first_bypass<=data_rd_rdata_i; d_first_ram_select<=1'b0; end
                    end
                    d_fill_error<=d_fill_error || data_rd_err_i || data_rd_rid_i!=1'b0;
                    if (d_beat==3'd7) begin
                        if (d_fill_error || data_rd_err_i || data_rd_rid_i!=1'b0) begin
                            d_result<=0; d_result_error<=1; d_state<=D_RESPONSE;
                        end else begin
                            if(request_way)begin
                                data_tags_second[d_index]<=d_address[31:6+D_INDEX_BITS];
                                data_valid_second[d_index]<=1; data_dirty_second[d_index]<=0;
                                d_second_tag<=d_address[31:6+D_INDEX_BITS]; d_second_valid<=1; d_second_dirty<=0;
                            end else begin
                                data_tags[d_index]<=d_address[31:6+D_INDEX_BITS];
                                data_valid[d_index]<=1; data_dirty[d_index]<=0;
                                d_tag<=d_address[31:6+D_INDEX_BITS]; d_valid<=1; d_dirty<=0;
                            end
                            d_state<=D_LOOKUP;
                        end
                    end else d_beat<=d_beat+3'd1;
                end
                D_WRITE_READ: begin
                    if(writeback_way)d_second_ram_select<=1'b1;
                    else d_first_ram_select<=1'b1;
                    d_state<=D_WRITE_BEATS;
                end
                D_WRITE_BEATS: if (data_wr_gnt_i) begin
                    if (d_beat==3'd7) begin
                        d_state<=D_WRITE_ACK;
                        // Accept a zero-latency completion on the final beat.
                        if (data_wr_bvalid_i && data_wr_bid_i==1'b0) begin
                            if (data_wr_berr_i) begin d_beat<=0; d_state<=D_WRITE_READ; end
                            else begin
                                if(writeback_way)data_dirty_second[writeback_index]<=0;
                                else data_dirty[writeback_index]<=0;
                                if (writeback_is_sweep) begin
                                    if (invalidate_data)begin
                                        if(writeback_way)data_valid_second[writeback_index]<=0;
                                        else data_valid[writeback_index]<=0;
                                    end
                                    if (sweep_is_last) begin
                                        for(n=0;n<I_LINES;n=n+1)begin instruction_valid[n]<=0;instruction_valid_second[n]<=0;end
                                        fence_pending<=fence_i || fence_d;
                                        invalidate_data<=fence_d;
                                        d_state<=D_IDLE;
                                    end else begin
                                        if(D_WAYS>1 && !sweep_way)sweep_way<=1;
                                        else begin sweep_way<=0; sweep_index<=sweep_index+1'b1; end
                                        d_state<=D_SWEEP_READ;
                                    end
                                end else begin d_beat<=0; d_state<=D_READ_COMMAND; end
                            end
                        end
                    end else begin
                        d_beat<=next_write_beat;
                        if(writeback_way)d_second_ram_select<=1'b1;
                        else d_first_ram_select<=1'b1;
                    end
                end
                D_WRITE_ACK: if (data_wr_bvalid_i && data_wr_bid_i==1'b0) begin
                    if (data_wr_berr_i) begin d_beat<=0; d_state<=D_WRITE_READ; end
                    else begin
                        if(writeback_way)data_dirty_second[writeback_index]<=0;
                        else data_dirty[writeback_index]<=0;
                        if (writeback_is_sweep) begin
                            if (invalidate_data)begin
                                if(writeback_way)data_valid_second[writeback_index]<=0;
                                else data_valid[writeback_index]<=0;
                            end
                            if (sweep_is_last) begin
                                for(n=0;n<I_LINES;n=n+1)begin instruction_valid[n]<=0;instruction_valid_second[n]<=0;end
                                fence_pending<=fence_i || fence_d;
                                invalidate_data<=fence_d;
                                d_state<=D_IDLE;
                            end else begin
                                if(D_WAYS>1 && !sweep_way)sweep_way<=1;
                                else begin sweep_way<=0; sweep_index<=sweep_index+1'b1; end
                                d_state<=D_SWEEP_READ;
                            end
                        end else begin d_beat<=0; d_state<=D_READ_COMMAND; end
                    end
                end
                D_IO_COMMAND: if (periph_gnt_i) begin
                    d_state<=D_IO_WAIT;
                    if (periph_rvalid_i) begin
                        d_result<=periph_rdata_i; d_result_error<=periph_err_i; d_state<=D_RESPONSE;
                    end
                end
                D_IO_WAIT: if (periph_rvalid_i) begin
                    d_result<=periph_rdata_i; d_result_error<=periph_err_i; d_state<=D_RESPONSE;
                end
                D_RESPONSE: if (d_complete) d_state<=D_IDLE;
                D_SWEEP_READ: begin
                    if(sweep_way)begin
                        d_tag<=data_tags_second[sweep_index];
                        d_valid<=data_valid_second[sweep_index]; d_dirty<=data_dirty_second[sweep_index];
                    end else begin
                        d_tag<=data_tags[sweep_index];
                        d_valid<=data_valid[sweep_index]; d_dirty<=data_dirty[sweep_index];
                    end
                    d_state<=D_SWEEP_CHECK;
                end
                D_SWEEP_CHECK: begin
                    if (d_valid && d_dirty) begin
                        writeback_address<={d_tag,sweep_index,6'b0};
                        writeback_way<=sweep_way;
                        writeback_index<=sweep_index; writeback_is_sweep<=1;
                        d_beat<=0; d_state<=D_WRITE_READ;
                    end else begin
                        if (invalidate_data)begin
                            if(sweep_way)data_valid_second[sweep_index]<=0;
                            else data_valid[sweep_index]<=0;
                        end
                        if (sweep_is_last) begin
                            for(n=0;n<I_LINES;n=n+1)begin instruction_valid[n]<=0;instruction_valid_second[n]<=0;end
                            fence_pending<=fence_i || fence_d;
                            invalidate_data<=fence_d;
                            d_state<=D_IDLE;
                        end else begin
                            if(D_WAYS>1 && !sweep_way)sweep_way<=1;
                            else begin sweep_way<=0; sweep_index<=sweep_index+1'b1; end
                            d_state<=D_SWEEP_READ;
                        end
                    end
                end
                default: begin end
            endcase
            // A held response has ready=0, so speculative data/tag reads
            // cannot replace its payload. Keep the original same-edge store
            // write forwarding and LRU/dirty bypass over these private reads.
            if(d_speculative_read)begin
                    d_first_ram_select<=1'b1; d_tag<=data_tags[next_d_index];
                    d_valid<=data_valid[next_d_index]; d_dirty<=data_dirty[next_d_index];
                    d_lru<=data_lru[next_d_index];
                    if(D_WAYS>1)begin
                        d_second_ram_select<=1'b1;
                        d_second_tag<=data_tags_second[next_d_index];
                        d_second_valid<=data_valid_second[next_d_index];
                        d_second_dirty<=data_dirty_second[next_d_index];
                    end else begin d_second_valid<=0; d_second_dirty<=0; end
                    if(d_complete && d_state==D_LOOKUP && next_d_index==d_index)
                        d_lru<=!selected_way;
                    // Explicit write-to-read forwarding avoids dependence on
                    // vendor-specific read-during-write memory behavior.
                    if (d_complete && d_state==D_LOOKUP && d_write && next_d_index==d_index) begin
                        if(selected_way)begin
                            d_second_dirty<=1;
                            if(next_d_segment==d_segment_index)begin d_second_bypass<=updated_data_segment; d_second_ram_select<=1'b0; end
                        end else begin
                            d_dirty<=1;
                            if(next_d_segment==d_segment_index)begin d_first_bypass<=updated_data_segment; d_first_ram_select<=1'b0; end
                        end
                    end
            end
            if(d_payload_free)begin
                d_address<=dmem_request_address; d_write<=dmem_request_write;
                d_wdata<=dmem_request_wdata; d_wstrb<=dmem_request_wstrb; d_size<=dmem_request_size;
            end
            if (new_d) begin
                // Preserve MMIO precedence and all original IO handshakes.
                // Only an accepted request owns this registered fault; held
                // responses, killed-load identity and alignment remain under
                // the unchanged cache/core transaction and exception rules.
                if (peripheral(dmem_request_address)) d_state<=D_IO_COMMAND;
                else if (!data_ram_mapped(dmem_request_address)) begin
                    d_result<=0; d_result_error<=1; d_state<=D_RESPONSE;
                end else begin
                    d_state<=D_LOOKUP;

                end
            end
        end
    end
endmodule
